#!/usr/bin/env python3
"""Turn the SVGs in Icons/ into Sources/Flip/UI/Icons.swift.

The icons are drawn as real vector paths rather than shipped as image
resources: a SwiftPM executable has no asset catalogue to compile an SVG into,
and a PNG would neither tint with `foregroundStyle` nor stay sharp at the sizes
these are drawn at. Emitting the path data keeps them behaving exactly like the
SF Symbols they replace.

Only the `d` strings are emitted; the app parses them once, on first use, and
caches the result. That keeps this file — and the compile — small.

Run from the Flip directory:  python3 tools/svg-to-swift.py
"""

