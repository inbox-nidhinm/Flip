D = re.compile(r'\sd="([^"]*)"')
VIEWBOX = re.compile(r'viewBox="([^"]*)"')
ALLOWED = set("MLHVCZmlhvcz")


def read(path):
    """Every `d` in the file, plus a check that nothing unexpected is in it."""
    text = path.read_text()

    box = VIEWBOX.search(text)
    if not box or box.group(1).split() != ["0", "0", "24", "24"]:
        sys.exit(f"{path}: expected a 0 0 24 24 viewBox, got {box and box.group(1)}")

    ds = D.findall(text)
    if not ds:
        sys.exit(f"{path}: no path data")

    for d in ds:
        for ch in d:
            if ch.isalpha() and ch not in ALLOWED:
                sys.exit(f"{path}: unsupported path command {ch!r} — "
                         "the Swift parser only knows M L H V C Z")
    return ds


def main():
    missing = [f for _, f in ICONS if f and not (SVG / f).exists()]
    if missing:
        sys.exit("missing: " + ", ".join(missing))

    lines = [
        "// Generated by tools/svg-to-swift.py — do not edit by hand.",
        "// Source artwork lives in Icons/. Re-run the script after changing it.",
        "",
        "import SwiftUI",
        "",
        "/// The app's icon set, as SVG path data on a 24×24 grid.",
        "///",
        "/// Parsed once on first use and cached. See `IconShape` for the drawing.",
        "enum Icon: String, CaseIterable {",
    ]

    for name, rel in ICONS:
        if rel is None:
            lines.append("")
            lines.append(f"    /// {name[2:]}")
            continue
        lines.append(f"    case {name}")

    lines.append("")
    lines.append("    /// The subpaths, in the order they are drawn.")
    lines.append("    var data: [String] {")
    lines.append("        switch self {")

    for name, rel in ICONS:
        if rel is None:
            continue
        ds = read(SVG / rel)
        body = ",\n".join(f'            "{d}"' for d in ds)
        lines.append(f"        case .{name}: return [   // {rel}")
        lines.append(body)
        lines.append("        ]")

    lines.append("        }")
    lines.append("    }")
    lines.append("}")
    lines.append("")

    OUT.write_text("\n".join(lines))
    n = sum(1 for _, f in ICONS if f)
    print(f"wrote {OUT.relative_to(ROOT)} — {n} icons")


if __name__ == "__main__":
    main()
